-- 001_store: the store schema (D10, D11 addition 1). Reset to the fixed seed before every
-- test (D3). The database itself enforces the money rules, so a bug in the code above it
-- can't create a second refund claim on an item or a second payout (D10).
-- Money is whole paise as bigint (M2 decision 2). Statuses are text with a CHECK, so a
-- later migration can add a value without ALTER TYPE (M2 smaller choices).

CREATE SCHEMA store;

CREATE TABLE store.customers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Unique contact fields, so the D3 leak check can match them verbatim (D3, D10).
    full_name   text NOT NULL CONSTRAINT customers_full_name_key UNIQUE,
    phone       text NOT NULL CONSTRAINT customers_phone_key UNIQUE,
    email       text NOT NULL CONSTRAINT customers_email_key UNIQUE,
    address     text NOT NULL CONSTRAINT customers_address_key UNIQUE,
    created_at  timestamptz NOT NULL
);

CREATE TABLE store.products (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL,
    category        text NOT NULL CONSTRAINT products_category_check CHECK (category IN (
                        'tshirt', 'shirt', 'hoodie', 'joggers', 'jeans', 'kurta', 'dress',
                        'shorts', 'innerwear', 'socks')),
    price_paise     bigint NOT NULL CHECK (price_paise > 0),
    -- Non-returnable flags; the rule itself lives in support.policy (D2a).
    final_sale      boolean NOT NULL DEFAULT false,
    custom_printed  boolean NOT NULL DEFAULT false
);

CREATE TABLE store.product_variants (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  bigint NOT NULL REFERENCES store.products (id),
    size        text NOT NULL,
    stock       integer NOT NULL CHECK (stock >= 0),
    UNIQUE (product_id, size),
    -- Target for exchanges: the new size must be a variant of the same product.
    UNIQUE (product_id, id)
);

CREATE TABLE store.orders (
    id                     text PRIMARY KEY CHECK (id ~ '^ORD-[0-9]+$'),
    customer_id            bigint NOT NULL REFERENCES store.customers (id),
    status                 text NOT NULL CONSTRAINT orders_status_check CHECK (status IN (
                               'placed', 'shipped', 'out_for_delivery', 'delivered', 'rto',
                               'cancelled', 'returned')),
    payment_method         text NOT NULL CONSTRAINT orders_payment_method_check
                               CHECK (payment_method IN ('cod', 'upi', 'card')),
    placed_at              timestamptz NOT NULL,
    shipped_at             timestamptz,
    delivered_at           timestamptz,
    rto_at                 timestamptz,
    cancelled_at           timestamptz,
    coupon_code            text,
    coupon_discount_paise  bigint NOT NULL DEFAULT 0 CHECK (coupon_discount_paise >= 0),
    shipping_fee_paise     bigint NOT NULL DEFAULT 0 CHECK (shipping_fee_paise >= 0),
    -- The return window counts from delivery, so a delivered order must say when (D2a).
    CONSTRAINT orders_delivered_at_check
        CHECK ((status IN ('delivered', 'returned')) = (delivered_at IS NOT NULL)),
    -- Target for ownership: a refund, exchange or handoff must name the order's own customer.
    UNIQUE (id, customer_id)
);

-- One row is one unit; there is no quantity column (D10).
CREATE TABLE store.order_items (
    id                text PRIMARY KEY CHECK (id ~ '^ITM-[0-9]+-[0-9]+$'),
    order_id          text NOT NULL REFERENCES store.orders (id),
    variant_id        bigint NOT NULL REFERENCES store.product_variants (id),
    -- The price paid at the time of the order, not today's catalogue price.
    unit_price_paise  bigint NOT NULL CHECK (unit_price_paise > 0),
    -- Target for "this item is in this order".
    UNIQUE (order_id, id)
);

CREATE TABLE store.refund_requests (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       text NOT NULL,
    customer_id    bigint NOT NULL,
    status         text NOT NULL DEFAULT 'pending' CONSTRAINT refund_requests_status_check
                       CHECK (status IN ('pending', 'approved', 'rejected')),
    amount_paise   bigint NOT NULL CHECK (amount_paise > 0),
    refund_method  text NOT NULL CONSTRAINT refund_requests_refund_method_check
                       CHECK (refund_method IN ('original_payment', 'store_credit')),
    reason         text NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    decided_at     timestamptz,
    -- The database refuses a request for someone else's order (D3 tightening 1, D7).
    FOREIGN KEY (order_id, customer_id) REFERENCES store.orders (id, customer_id),
    -- Targets for the composite keys below.
    UNIQUE (id, status),
    UNIQUE (id, order_id),
    UNIQUE (id, status, amount_paise, refund_method)
);

-- The refund-item lock (D10 rule b, M2 decision 3). Each row copies its request's status,
-- and Postgres keeps the copy in sync (ON UPDATE CASCADE). The partial unique index then
-- allows one claim per item among requests that weren't rejected: pending, approved and
-- paid-out requests all lock the item. A unique index can't race, so two simultaneous
-- requests for one item produce exactly one row.
CREATE TABLE store.refund_request_items (
    refund_request_id  bigint NOT NULL,
    order_id           text NOT NULL,
    order_item_id      text NOT NULL,
    request_status     text NOT NULL DEFAULT 'pending',
    PRIMARY KEY (refund_request_id, order_item_id),
    FOREIGN KEY (refund_request_id, request_status)
        REFERENCES store.refund_requests (id, status) ON UPDATE CASCADE,
    -- The item must be in the request's own order.
    FOREIGN KEY (refund_request_id, order_id) REFERENCES store.refund_requests (id, order_id),
    FOREIGN KEY (order_id, order_item_id) REFERENCES store.order_items (order_id, id)
);

CREATE UNIQUE INDEX refund_request_items_one_active_claim
    ON store.refund_request_items (order_item_id) WHERE request_status <> 'rejected';

-- One payout per refund request, only for an approved request, for its exact amount and
-- method (D10 rule c, M2 decision 3). ON UPDATE RESTRICT: once a payout exists, the
-- request's status, amount and method can't change, so a paid request can't be rejected.
CREATE TABLE store.payouts (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_request_id  bigint NOT NULL CONSTRAINT payouts_refund_request_id_key UNIQUE,
    request_status     text NOT NULL DEFAULT 'approved' CHECK (request_status = 'approved'),
    amount_paise       bigint NOT NULL,
    refund_method      text NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (refund_request_id, request_status, amount_paise, refund_method)
        REFERENCES store.refund_requests (id, status, amount_paise, refund_method)
        ON UPDATE RESTRICT
);

-- One exchange per item (D2a "once per item", D7 tightening 3).
CREATE TABLE store.exchanges (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        text NOT NULL,
    order_item_id   text NOT NULL CONSTRAINT exchanges_order_item_id_key UNIQUE,
    customer_id     bigint NOT NULL,
    product_id      bigint NOT NULL,
    new_variant_id  bigint NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (order_id, customer_id) REFERENCES store.orders (id, customer_id),
    FOREIGN KEY (order_id, order_item_id) REFERENCES store.order_items (order_id, id),
    -- The new size must be a variant of product_id. That product_id is the original item's
    -- product is checked by M3's request_exchange, not here.
    FOREIGN KEY (product_id, new_variant_id) REFERENCES store.product_variants (product_id, id)
);

CREATE TABLE store.handoffs (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      bigint NOT NULL REFERENCES store.customers (id),
    order_id         text,
    -- The seven reason codes (D7 tightening 2, D14).
    reason           text NOT NULL CONSTRAINT handoffs_reason_check CHECK (reason IN (
                         'angry', 'two_failed', 'damaged', 'technical', 'complaint',
                         'cancellation', 'human_requested')),
    summary          text NOT NULL,
    status           text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    -- The foreign key to log.conversations arrives in 002_log.sql (D10 allows store -> log).
    conversation_id  bigint,
    created_at       timestamptz NOT NULL DEFAULT now(),
    -- A handoff that names an order must name one of the customer's own orders.
    FOREIGN KEY (order_id, customer_id) REFERENCES store.orders (id, customer_id)
);

-- Session tokens for the "continue as" picker (D11 tightening 1, addition 1). In store, so
-- the per-test reset clears them.
CREATE TABLE store.sessions (
    token        text PRIMARY KEY,
    customer_id  bigint NOT NULL REFERENCES store.customers (id),
    created_at   timestamptz NOT NULL DEFAULT now()
);
