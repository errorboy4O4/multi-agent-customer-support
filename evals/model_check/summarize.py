"""Writes evals/results/m1-model-check/summary.md from the run files (D3, D9).

    uv run --project backend python evals/model_check/summarize.py

Every number comes from the JSON run files. Runs are grouped by their full settings, so
runs with a different model, effort or prompt version never mix. T1 needs exactly 3
valid runs: with fewer or more it says "not computable" instead of picking runs.
"""

import json
import sys
from pathlib import Path
from statistics import fmean
from typing import Any

if __package__ in (None, ""):  # run as a script: put the repo root on the path
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from evals.model_check.scoring import T1_RUNS, meets_t1  # noqa: E402

RESULTS_DIR = Path(__file__).resolve().parents[2] / "evals" / "results" / "m1-model-check"
HEADER = (
    "# M1 model check: summary\n\n"
    "Early estimates: draft prompt, canned tool results (milestones.md). "
    "Generated by `summarize.py` from the JSON run files in this folder.\n"
)


def _settings_key(run: dict[str, Any]) -> tuple[Any, ...]:
    s = run["settings"]
    return (s["provider"], s["model"], s["temperature"], s["effort"], s["prompt_version"])


def _mean(values: list[float], fmt: str) -> str:
    return format(fmean(values), fmt) if values else "n/a"


def _section(runs: list[dict[str, Any]]) -> str:
    s = runs[0]["settings"]
    valid = sorted((r for r in runs if r["valid"]), key=lambda r: r["run_index"])
    invalid = [r for r in runs if not r["valid"]]
    scores = [r["score"] for r in valid]
    wrong_refunds = sum(r["wrong_refunds"] for r in valid)
    if len(valid) == T1_RUNS:
        t1 = "**PASS**" if meets_t1(scores, wrong_refunds) else "**FAIL**"
    else:
        t1 = f"not computable (needs exactly {T1_RUNS} valid runs, has {len(valid)})"
    convos = [c for r in valid for c in r["conversations"]]
    ok = [c for c in convos if not c["error"]]
    missing = sum(r["missing_usage"] for r in valid) + sum(c["missing_usage"] for c in convos)
    failed_convo = sum(c["error_calls"] for c in convos)
    failed_cases = sum(
        rec["error_class"] is not None for r in valid for c in r["cases"] for rec in c["records"]
    )
    lines = [
        f"## {s['provider']} · `{s['model']}`",
        "",
        f"Settings: temperature {s['temperature']}, effort {s['effort']}, "
        f"prompt version {s['prompt_version']}.",
        "",
        f"- valid runs: {len(valid)}, invalid runs: {len(invalid)}",
        "- score per run: " + (", ".join(f"{x:.3f}" for x in scores) or "n/a"),
        f"- mean score: {_mean(scores, '.3f')}",
        f"- wrong refunds: {wrong_refunds}",
        f"- T1: {t1}",
        f"- errors (provider, after reruns): {sum(r['errors'] for r in valid)}",
        f"- mean requests per conversation: {_mean([c['requests'] for c in ok], '.1f')}; "
        f"failed attempts (they count against the quota): {failed_convo} in conversations, "
        f"{failed_cases} in cases",
        f"- mean input tokens per conversation: {_mean([c['input_tokens'] for c in ok], '.0f')}",
        "- mean output tokens per conversation (including thinking): "
        + _mean([c["output_tokens"] for c in ok], ".0f"),
        f"- unmatched calls: {sum(c['unmatched_calls'] for c in convos)}, "
        f"invalid calls: {sum(c['invalid_calls'] for c in convos)}, "
        f"conversations that hit the call cap: {sum(c['hit_cap'] for c in convos)}",
        f"- conversations with a provider error (left out of means): {len(convos) - len(ok)}",
        f"- calls with no usage data: {missing}",
    ]
    return "\n".join(lines) + "\n"


def summarize(run_files: list[dict[str, Any]]) -> str:
    groups: dict[tuple[Any, ...], list[dict[str, Any]]] = {}
    for run in run_files:
        groups.setdefault(_settings_key(run), []).append(run)
    sections = [_section(groups[k]) for k in sorted(groups, key=str)]
    return HEADER + "\n" + "\n".join(sections)


def main() -> int:
    files = sorted(RESULTS_DIR.glob("*.json"))
    if not files:
        print(f"no run files in {RESULTS_DIR}")
        return 1
    runs = [json.loads(p.read_text(encoding="utf-8")) for p in files]
    out = RESULTS_DIR / "summary.md"
    out.write_text(summarize(runs), encoding="utf-8")
    print(f"wrote {out} from {len(runs)} run files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
